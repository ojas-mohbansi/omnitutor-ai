// Tests for the extended TestSetItem schema and updated testSetGaps (Req 7.5–7.7).
import assert from "node:assert/strict";
import { describe, it } from "node:test";
import { TestSetItem, testSetGaps, type TestSetItem as TestSetItemType } from "../src/eval";

const minimalItem = (id: string, modality: TestSetItemType["modality"] = "pdf"): Record<string, unknown> => ({
  id,
  question: "What is CPU scheduling?",
  modality,
  needsFigure: false,
  groundTruth: "A process of selecting the next process for CPU execution.",
  expected: modality === "off_material" ? [] : [{ sourceType: "PDF", filename: "chapter.pdf", page: 1 }],
});

describe("TestSetItem extended schema", () => {
  it("parses a minimal item and applies all four defaults (Req 7.5)", () => {
    const result = TestSetItem.parse(minimalItem("item-1"));
    assert.equal(result.difficulty, "medium");
    assert.equal(result.topic, "");
    assert.equal(result.answerType, "factual");
    assert.equal(result.autoGenerated, false);
  });

  it("accepts all four new fields when provided", () => {
    const result = TestSetItem.parse({
      ...minimalItem("item-2"),
      difficulty: "hard",
      topic: "CPU Scheduling",
      answerType: "inferential",
      autoGenerated: true,
    });
    assert.equal(result.difficulty, "hard");
    assert.equal(result.topic, "CPU Scheduling");
    assert.equal(result.answerType, "inferential");
    assert.equal(result.autoGenerated, true);
  });

  it("rejects invalid difficulty value", () => {
    assert.throws(() => TestSetItem.parse({ ...minimalItem("item-3"), difficulty: "extreme" }));
  });

  it("rejects invalid answerType value", () => {
    assert.throws(() => TestSetItem.parse({ ...minimalItem("item-4"), answerType: "opinion" }));
  });
});

describe("testSetGaps", () => {
  it("empty array reports all gaps including hard:0/2 (Req 7.6)", () => {
    const gaps = testSetGaps([]);
    assert.ok(gaps.includes("pdf: 0/5"), `missing pdf: ${gaps}`);
    assert.ok(gaps.includes("pptx: 0/5"), `missing pptx: ${gaps}`);
    assert.ok(gaps.includes("video: 0/5"), `missing video: ${gaps}`);
    assert.ok(gaps.includes("off_material: 0/5"), `missing off_material: ${gaps}`);
    assert.ok(gaps.includes("needsFigure: 0/2"), `missing needsFigure: ${gaps}`);
    assert.ok(gaps.includes("hard: 0/2"), `missing hard:0/2 gap in: ${gaps}`);
  });

  it("reports hard:1/2 when only one hard item exists (Req 7.6)", () => {
    const items = [TestSetItem.parse({ ...minimalItem("h1"), difficulty: "hard" })];
    const gaps = testSetGaps(items);
    assert.ok(gaps.includes("hard: 1/2"), `expected hard:1/2 in: ${gaps}`);
  });

  it("does NOT report hard gap when 2+ hard items exist (Req 7.6)", () => {
    const items = [
      TestSetItem.parse({ ...minimalItem("h1"), difficulty: "hard" }),
      TestSetItem.parse({ ...minimalItem("h2"), difficulty: "hard" }),
    ];
    const gaps = testSetGaps(items);
    assert.ok(!gaps.some((g) => g.startsWith("hard:")), `unexpected hard gap: ${gaps}`);
  });

  it("still reports modality and needsFigure gaps (Req 7.7)", () => {
    const gaps = testSetGaps([]);
    assert.ok(gaps.some((g) => g.startsWith("pdf:")));
    assert.ok(gaps.some((g) => g.startsWith("needsFigure:")));
  });
});
