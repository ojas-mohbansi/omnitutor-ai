// Eval Q&A generation: reads highest-quality chunks from Postgres → calls Gemini (via @sc/core)
// → assembles TestSetItem[] → writes tools/eval/testset.json.
// Run: npm run dataset:generate-eval [courseId] [--count N]
// Requirements: 10.x, 11.x
import { writeFileSync, mkdirSync } from "node:fs";
import { join, resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import process from "node:process";
import { z } from "zod";
import { prisma } from "@sc/db";
import { generateJson } from "@sc/core";
import { TestSet, TestSetItem, testSetGaps, type TestSetItem as TestSetItemType } from "@sc/schemas";

// ── Constants ──
const DEFAULT_COUNT = 20;
const MAX_COUNT = 500;
const MIN_COUNT = 1;

// ── Repo root ──
function repoRoot(): string {
  return process.env.REPO_ROOT ?? resolve(new URL("../../../..", import.meta.url).pathname);
}

// ── Gemini schema for one Q&A generation call ──
export const QAExtraction = z.object({
  items: z.array(z.object({
    question:    z.string().min(10),
    groundTruth: z.string().min(1),
    answerType:  z.enum(["factual", "numerical", "inferential"]),
    difficulty:  z.enum(["easy", "medium", "hard"]),
    needsFigure: z.boolean(),
  })).min(1).max(3),
});
export type QAExtraction = z.infer<typeof QAExtraction>;

// ── Row types ──
type ChunkRow = {
  id: string; kind: string; seq: number; title: string | null; content: string; section: string | null;
  page: number | null; slide: number | null; tStart: number | null; tEnd: number | null;
  qualityScore: number | null; topicId: string | null;
  source: { id: string; type: string; filename: string };
  topic: { id: string; name: string } | null;
};
type TopicRow = { id: string; name: string; seq: number };

// ── Pure helpers ──

/** Build the Gemini prompt for a single chunk. */
export function buildPrompt(chunk: ChunkRow, topicName: string, sourceName: string): string {
  const locator =
    chunk.page != null ? `PDF page ${chunk.page}` :
    chunk.slide != null ? `slide ${chunk.slide}` :
    chunk.tStart != null ? `video ${chunk.tStart}s–${chunk.tEnd}s` : "unknown location";

  return `You are writing evaluation questions for a study assistant about a course on ${topicName}.

Source: "${sourceName}" (${locator})
Topic: ${topicName}
${chunk.title ? `Section: ${chunk.title}` : ""}

Content:
${chunk.content}

Generate 1–3 exam-style questions that a student could answer ONLY from this content. For each:
- question: a specific, unambiguous question
- groundTruth: a concise, accurate answer
- answerType: "factual" (recall a fact), "numerical" (compute a number), or "inferential" (reason from the content)
- difficulty: "easy" (straightforward), "medium" (requires understanding), or "hard" (requires synthesis)
- needsFigure: true if the question requires looking at a diagram/figure to answer

Rules:
- Do not ask about things not present in this content.
- Do not generate trivial yes/no questions.
- At most one numerical question per chunk.
- If the content has no figures, set needsFigure to false for all items.`;
}

/** Assemble a TestSetItem from a raw Gemini Q&A item and chunk metadata. */
export function assembleTestItem(
  raw: QAExtraction["items"][number],
  chunk: ChunkRow,
  idx: number,
): TestSetItemType {
  const source = chunk.source;
  const topic = chunk.topic;
  const modality =
    source.type === "PDF" ? "pdf" :
    source.type === "PPTX" ? "pptx" :
    "video" as const;

  type Expected = TestSetItemType["expected"][number];
  let expected: Expected[];
  if (source.type === "PDF" && chunk.page != null) {
    expected = [{ sourceType: "PDF", filename: source.filename, page: chunk.page }];
  } else if (source.type === "PPTX" && chunk.slide != null) {
    expected = [{ sourceType: "PPTX", filename: source.filename, slide: chunk.slide }];
  } else if (source.type === "VIDEO" && chunk.tStart != null && chunk.tEnd != null) {
    expected = [{ sourceType: "VIDEO", filename: source.filename, tStart: chunk.tStart, tEnd: chunk.tEnd }];
  } else {
    expected = [];
  }

  return TestSetItem.parse({
    id:            `gen-${chunk.id}-${idx}`,
    question:      raw.question,
    modality,
    needsFigure:   raw.needsFigure,
    groundTruth:   raw.groundTruth,
    expected,
    difficulty:    raw.difficulty,
    topic:         topic?.name ?? "",
    answerType:    raw.answerType,
    autoGenerated: true,
  });
}

// ── Chunk candidate selection ──

/**
 * Selects candidate chunks using the slot algorithm from the design:
 * - floor(targetCount * 0.6) slots from topic-balanced pool
 * - at most floor(targetCount * 0.25) off-material (no topicId) slots
 * - at least max(2, floor(targetCount * 0.1)) FIGURE chunks
 * - remaining slots filled with next-highest qualityScore chunks
 */
export function selectCandidates(
  topics: TopicRow[],
  chunks: ChunkRow[],
  targetCount: number,
): ChunkRow[] {
  // Sort by qualityScore desc (nulls last → treated as 0)
  const sorted = [...chunks].sort((a, b) =>
    (b.qualityScore ?? 0) - (a.qualityScore ?? 0)
  );

  const topicSlots = Math.floor(targetCount * 0.6);
  const offMaterialSlots = Math.floor(targetCount * 0.25);
  const figureSlots = Math.max(2, Math.floor(targetCount * 0.1));
  const perTopic = topics.length > 0 ? Math.ceil(topicSlots / topics.length) : topicSlots;

  const selected = new Set<string>();
  const result: ChunkRow[] = [];

  // Topic-balanced pool
  for (const topic of topics) {
    let added = 0;
    for (const c of sorted) {
      if (added >= perTopic) break;
      if (c.topicId === topic.id && !selected.has(c.id)) {
        selected.add(c.id);
        result.push(c);
        added++;
      }
    }
  }

  // Figure chunks (at least figureSlots)
  let figureAdded = result.filter(c => c.kind === "FIGURE").length;
  for (const c of sorted) {
    if (figureAdded >= figureSlots) break;
    if (c.kind === "FIGURE" && !selected.has(c.id)) {
      selected.add(c.id);
      result.push(c);
      figureAdded++;
    }
  }

  // Fill remaining (excluding off-material slots which are handwritten)
  const remaining = targetCount - offMaterialSlots - result.length;
  let filled = 0;
  for (const c of sorted) {
    if (filled >= remaining) break;
    if (!selected.has(c.id)) {
      selected.add(c.id);
      result.push(c);
      filled++;
    }
  }

  return result.slice(0, targetCount - offMaterialSlots);
}

// ── Hardcoded off-material items ──
function offMaterialItems(): TestSetItemType[] {
  const base = { modality: "off_material" as const, needsFigure: false, groundTruth: "", expected: [], autoGenerated: false };
  return [
    TestSetItem.parse({ ...base, id: "off-1", question: "Who invented the internet?", topic: "", difficulty: "easy", answerType: "factual" }),
    TestSetItem.parse({ ...base, id: "off-2", question: "What is the capital of France?", topic: "", difficulty: "easy", answerType: "factual" }),
    TestSetItem.parse({ ...base, id: "off-3", question: "What is the current stock price of Apple?", topic: "", difficulty: "easy", answerType: "factual" }),
    TestSetItem.parse({ ...base, id: "off-4", question: "How do you bake a chocolate cake?", topic: "", difficulty: "easy", answerType: "factual" }),
    TestSetItem.parse({ ...base, id: "off-5", question: "What is the latest version of Python?", topic: "", difficulty: "easy", answerType: "factual" }),
  ];
}

// ── main() ──
async function main(): Promise<void> {
  // Validate env
  const missingVars: string[] = [];
  if (!process.env.APP_GEMINI_API_KEY) missingVars.push("APP_GEMINI_API_KEY");
  if (!process.env.LLM_MODEL_FAST) missingVars.push("LLM_MODEL_FAST");
  if (missingVars.length > 0) {
    process.stderr.write(`Error: Missing environment variables: ${missingVars.join(", ")}. Set them in .env.\n`);
    process.exit(1);
  }

  // Parse args
  const args = process.argv.slice(2);
  let courseIdArg: string | undefined;
  let targetCount = DEFAULT_COUNT;

  for (let i = 0; i < args.length; i++) {
    if (args[i] === "--count" && args[i + 1]) {
      const n = Number(args[++i]);
      if (!Number.isInteger(n) || n < MIN_COUNT || n > MAX_COUNT) {
        process.stderr.write(`Error: --count must be an integer between ${MIN_COUNT} and ${MAX_COUNT}.\n`);
        process.exit(1);
      }
      targetCount = n;
    } else if (!args[i].startsWith("--")) {
      courseIdArg = args[i];
    }
  }

  // Resolve course
  let courseId: string;
  if (courseIdArg) {
    const course = await prisma.course.findUnique({ where: { id: courseIdArg } });
    if (!course) {
      const all = await prisma.course.findMany({ select: { id: true } });
      process.stderr.write(`Error: Course "${courseIdArg}" not found. Available: ${all.map(c => c.id).join(", ")}\n`);
      await prisma.$disconnect();
      process.exit(1);
    }
    courseId = course.id;
  } else {
    const courses = await prisma.course.findMany({
      where: { sources: { some: { status: "READY" } } },
      select: { id: true },
    });
    if (courses.length === 0) {
      process.stderr.write("Error: No courses with READY sources found.\n");
      await prisma.$disconnect();
      process.exit(1);
    }
    courseId = courses[0].id;
  }

  // Fetch topics and chunks
  const [topics, allChunks] = await Promise.all([
    prisma.topic.findMany({ where: { courseId }, select: { id: true, name: true, seq: true }, orderBy: { seq: "asc" } }),
    prisma.chunk.findMany({
      where: { source: { courseId, status: "READY" } },
      include: {
        source: { select: { id: true, type: true, filename: true } },
        topic: { select: { id: true, name: true } },
      },
      orderBy: { seq: "asc" },
    }),
  ]);

  // Warn if all qualityScore are null
  const allNull = allChunks.every(c => c.qualityScore === null);
  if (allNull) {
    process.stderr.write("Warning: all chunks have null qualityScore — ordering by seq. Re-ingest after deploying this feature for scored chunks.\n");
  }

  // Warn if fewer chunks than targetCount
  if (allChunks.length < targetCount) {
    process.stderr.write(`Warning: only ${allChunks.length} chunks available (requested ${targetCount}). Generating items for all chunks.\n`);
  }

  // Select candidates
  const candidates = selectCandidates(topics, allChunks as ChunkRow[], targetCount);

  // Generate Q&A items
  const generatedItems: TestSetItemType[] = [];
  let skipped = 0;

  for (const chunk of candidates) {
    const topicName = chunk.topic?.name ?? "General";
    const cacheKey = `eval-gen|v1|${chunk.id}`;
    try {
      const result = await generateJson({
        role: "fast",
        schema: QAExtraction,
        system: "You generate exam questions for a study assistant. Return valid JSON only.",
        parts: [{ text: buildPrompt(chunk as ChunkRow, topicName, chunk.source.filename) }],
        cacheKey,
      });
      for (let i = 0; i < result.data.items.length; i++) {
        generatedItems.push(assembleTestItem(result.data.items[i], chunk as ChunkRow, i));
      }
    } catch (e) {
      process.stderr.write(`Warning: generateJson failed for chunk ${chunk.id} — skipping. Error: ${e}\n`);
      skipped++;
    }
  }

  // Add off-material items
  const allItems: TestSetItemType[] = [...generatedItems, ...offMaterialItems()];

  // Validate with TestSet.parse
  let validated: TestSetItemType[];
  try {
    validated = TestSet.parse(allItems);
  } catch (e) {
    process.stderr.write(`Error: TestSet.parse() failed:\n${e}\n`);
    await prisma.$disconnect();
    process.exit(1);
  }

  // Write output
  const outPath = join(repoRoot(), "tools", "eval", "testset.json");
  mkdirSync(dirname(outPath), { recursive: true });
  writeFileSync(outPath, JSON.stringify(validated, null, 2), "utf8");

  // Report
  const gaps = testSetGaps(validated);
  console.log(`Generated ${validated.length} items (${skipped} chunks skipped) → tools/eval/testset.json`);
  if (gaps.length === 0) {
    console.log("no gaps detected");
  } else {
    console.log(`Gaps: ${gaps.join(", ")}`);
  }

  await prisma.$disconnect();
}

// Only invoke main() when this file is run directly (not imported by tests).
const isMain = process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1]);
if (isMain) {
  main().catch((e) => { console.error(e); process.exit(1); });
}
