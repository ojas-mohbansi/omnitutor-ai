// Unit tests for generate-eval.ts pure helpers (Requirements 10.x, 11.x, Properties 6, 7).
import assert from "node:assert/strict";
import { describe, it } from "node:test";
import { TestSet } from "@sc/schemas";
import { buildPrompt, assembleTestItem, selectCandidates, type QAExtraction } from "../src/generate-eval";

// ── Fixtures ──
function makeChunk(overrides: Record<string, unknown> = {}) {
  return {
    id: "chunk-001", kind: "TEXT", seq: 0, title: "CPU Scheduling", content: "CPU scheduling allocates the CPU.",
    section: "3.2", page: 5, slide: null, tStart: null, tEnd: null,
    qualityScore: 0.8, topicId: "topic-1",
    source: { id: "src-1", type: "PDF", filename: "chapter.pdf" },
    topic: { id: "topic-1", name: "Process Scheduling" },
    ...overrides,
  };
}

function makeRawItem(overrides: Partial<QAExtraction["items"][number]> = {}): QAExtraction["items"][number] {
  return {
    question: "What is CPU scheduling?",
    groundTruth: "CPU scheduling selects processes for CPU execution.",
    answerType: "factual",
    difficulty: "medium",
    needsFigure: false,
    ...overrides,
  };
}

const mockTopics = [
  { id: "topic-1", name: "Scheduling", seq: 0 },
  { id: "topic-2", name: "Memory",     seq: 1 },
];

describe("buildPrompt", () => {
  it("includes topic name and source filename", () => {
    const prompt = buildPrompt(makeChunk() as any, "Process Scheduling", "chapter.pdf");
    assert.ok(prompt.includes("Process Scheduling"), "prompt should mention the topic");
    assert.ok(prompt.includes("chapter.pdf"), "prompt should mention the source filename");
  });

  it("includes the chunk content", () => {
    const prompt = buildPrompt(makeChunk() as any, "Process Scheduling", "chapter.pdf");
    assert.ok(prompt.includes("CPU scheduling allocates the CPU."), "prompt should include chunk content");
  });

  it("includes PDF page locator", () => {
    const prompt = buildPrompt(makeChunk() as any, "Process Scheduling", "chapter.pdf");
    assert.ok(prompt.includes("PDF page 5"), "should include PDF page");
  });

  it("includes video timestamp locator for VIDEO chunks", () => {
    const videoChunk = makeChunk({ page: null, tStart: 30.5, tEnd: 60.5 });
    const prompt = buildPrompt(videoChunk as any, "Scheduling", "lecture.mp4");
    assert.ok(prompt.includes("30.5s"), "should include tStart");
    assert.ok(prompt.includes("60.5s"), "should include tEnd");
  });
});

describe("assembleTestItem (Requirements 11.1, 11.2, 11.3)", () => {
  it("sets autoGenerated=true (Req 11.1)", () => {
    const item = assembleTestItem(makeRawItem(), makeChunk() as any, 0);
    assert.equal(item.autoGenerated, true);
  });

  it("sets topic from chunk.topic.name (Req 11.2)", () => {
    const item = assembleTestItem(makeRawItem(), makeChunk() as any, 0);
    assert.equal(item.topic, "Process Scheduling");
    assert.notEqual(item.topic, "");
  });

  it("maps PDF → 'pdf' modality (Req 11.3)", () => {
    const item = assembleTestItem(makeRawItem(), makeChunk() as any, 0);
    assert.equal(item.modality, "pdf");
  });

  it("maps PPTX → 'pptx' modality (Req 11.3)", () => {
    const pptxChunk = makeChunk({ source: { id: "src-2", type: "PPTX", filename: "deck.pptx" }, page: null, slide: 3 });
    const item = assembleTestItem(makeRawItem(), pptxChunk as any, 0);
    assert.equal(item.modality, "pptx");
    assert.deepEqual(item.expected, [{ sourceType: "PPTX", filename: "deck.pptx", slide: 3 }]);
  });

  it("maps VIDEO → 'video' modality (Req 11.3)", () => {
    const videoChunk = makeChunk({ source: { id: "src-3", type: "VIDEO", filename: "lecture.mp4" }, page: null, tStart: 10.0, tEnd: 40.0 });
    const item = assembleTestItem(makeRawItem(), videoChunk as any, 0);
    assert.equal(item.modality, "video");
    assert.deepEqual(item.expected, [{ sourceType: "VIDEO", filename: "lecture.mp4", tStart: 10.0, tEnd: 40.0 }]);
  });

  it("assembled items pass TestSet.parse (Property 6)", () => {
    const items = [
      assembleTestItem(makeRawItem({ difficulty: "hard" }), makeChunk() as any, 0),
      assembleTestItem(makeRawItem(), makeChunk({ id: "chunk-002" }) as any, 0),
    ];
    assert.doesNotThrow(() => TestSet.parse(items));
  });
});

describe("selectCandidates (Requirement 10.6)", () => {
  const makeChunkList = (n: number) =>
    Array.from({ length: n }, (_, i) => makeChunk({ id: `chunk-${i}`, topicId: i % 2 === 0 ? "topic-1" : "topic-2", qualityScore: (n - i) / n }));

  it("returns at most targetCount - offMaterialSlots candidates", () => {
    const chunks = makeChunkList(20);
    const candidates = selectCandidates(mockTopics, chunks as any[], 10);
    // offMaterialSlots = floor(10 * 0.25) = 2, so max = 10 - 2 = 8
    assert.ok(candidates.length <= 8, `should be ≤ 8, got ${candidates.length}`);
  });

  it("deduplicates candidates (no chunk appears twice)", () => {
    const chunks = makeChunkList(30);
    const candidates = selectCandidates(mockTopics, chunks as any[], 20);
    const ids = candidates.map(c => c.id);
    assert.equal(new Set(ids).size, ids.length, "candidates should be deduplicated");
  });

  it("when all qualityScores are null, still returns chunks without error", () => {
    const nullChunks = makeChunkList(10).map(c => ({ ...c, qualityScore: null }));
    assert.doesNotThrow(() => selectCandidates(mockTopics, nullChunks as any[], 5));
  });

  it("includes FIGURE chunks when available (Property 7)", () => {
    const chunks = [
      ...makeChunkList(8),
      makeChunk({ id: "figure-1", kind: "FIGURE", qualityScore: 0.9, topicId: "topic-1" }),
      makeChunk({ id: "figure-2", kind: "FIGURE", qualityScore: 0.85, topicId: "topic-2" }),
    ];
    const candidates = selectCandidates(mockTopics, chunks as any[], 10);
    const figureChunks = candidates.filter(c => c.kind === "FIGURE");
    assert.ok(figureChunks.length >= 2, `should include ≥2 figure chunks, got ${figureChunks.length}`);
  });
});
